import React, { useState } from 'react';
import { Mail, Send, X, Check, AlertCircle, Sparkles } from 'lucide-react';
import { sendManualEmail } from '../api';

export default function EmailModal({ isOpen, onClose, sessionId }) {
  const [to, setTo] = useState('');
  const [subject, setSubject] = useState('');
  const [body, setBody] = useState('');
  const [isSending, setIsSending] = useState(false);
  const [statusMessage, setStatusMessage] = useState(null); // { type: 'success' | 'error', text: '' }

  if (!isOpen) return null;

  const validateEmail = (email) => {
    return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email.trim());
  };

  const handleSend = async (e) => {
    e.preventDefault();
    setStatusMessage(null);

    if (!to.trim()) {
      setStatusMessage({ type: 'error', text: 'Recipient email address is required.' });
      return;
    }
    if (!validateEmail(to)) {
      setStatusMessage({ type: 'error', text: 'Please enter a valid email address (e.g. name@example.com).' });
      return;
    }
    if (!body.trim()) {
      setStatusMessage({ type: 'error', text: 'Email body cannot be empty.' });
      return;
    }

    setIsSending(true);
    try {
      const res = await sendManualEmail(to.trim(), subject.trim() || '(No Subject)', body.trim(), sessionId);
      setStatusMessage({
        type: 'success',
        text: `Email successfully dispatched to ${to.trim()} via Gmail SMTP!`,
      });
      setTimeout(() => {
        setTo('');
        setSubject('');
        setBody('');
        setStatusMessage(null);
        onClose();
      }, 2200);
    } catch (err) {
      setStatusMessage({ type: 'error', text: err.message || 'Failed to send email.' });
    } finally {
      setIsSending(false);
    }
  };

  const setTemplate = (tmplSubject, tmplBody) => {
    setSubject(tmplSubject);
    setBody(tmplBody);
  };

  return (
    <div className="modal-backdrop" onClick={onClose}>
      <div className="email-modal-card" onClick={(e) => e.stopPropagation()}>
        <div className="modal-header">
          <div className="modal-title-wrap">
            <div className="modal-icon-badge">
              <Mail size={18} color="#06b6d4" />
            </div>
            <div>
              <h3>Manual Email Dispatch</h3>
              <span className="modal-sub">
                Authenticated Sender: <strong>bookpdf247@gmail.com</strong> (Gmail SMTP :587)
              </span>
            </div>
          </div>
          <button className="modal-close-btn" onClick={onClose} title="Close window">
            <X size={18} />
          </button>
        </div>

        <form onSubmit={handleSend} className="modal-body-form">
          {statusMessage && (
            <div className={`status-banner ${statusMessage.type}`}>
              {statusMessage.type === 'success' ? <Check size={16} /> : <AlertCircle size={16} />}
              <span>{statusMessage.text}</span>
            </div>
          )}

          <div className="form-group">
            <label>Recipient Email Address *</label>
            <input
              type="email"
              className="form-input"
              placeholder="e.g. client@example.com, colleague@company.org"
              value={to}
              onChange={(e) => setTo(e.target.value)}
              required
              disabled={isSending}
            />
          </div>

          <div className="form-group">
            <label>Subject Title</label>
            <input
              type="text"
              className="form-input"
              placeholder="e.g. Project Summary & Ragnarok AI Analysis"
              value={subject}
              onChange={(e) => setSubject(e.target.value)}
              disabled={isSending}
            />
          </div>

          <div className="quick-templates-bar">
            <span style={{ fontSize: '0.74rem', color: 'var(--text-muted)' }}>Quick Templates:</span>
            <button
              type="button"
              className="template-chip"
              onClick={() =>
                setTemplate(
                  'Project Progress & Analysis Report',
                  'Hi there,\n\nPlease find attached the latest project progress report generated by Ragnarok AI Sovereign Agent.\n\nBest regards,\nRagnarok Agent'
                )
              }
            >
              <Sparkles size={11} /> Project Report
            </button>
            <button
              type="button"
              className="template-chip"
              onClick={() =>
                setTemplate(
                  'Follow-Up Regarding Action Items',
                  'Hello,\n\nFollowing up on our recent action items. Please let me know if you need any additional information.\n\nRegards,\nRagnarok Agent'
                )
              }
            >
              Follow-Up
            </button>
          </div>

          <div className="form-group">
            <label>Message Content *</label>
            <textarea
              className="form-textarea"
              rows={6}
              placeholder="Type your message content here..."
              value={body}
              onChange={(e) => setBody(e.target.value)}
              required
              disabled={isSending}
            />
          </div>

          <div className="modal-actions-bar">
            <button type="button" className="btn-outline" onClick={onClose} disabled={isSending}>
              Cancel
            </button>
            <button
              type="submit"
              className="btn-primary"
              disabled={isSending || !to.trim() || !body.trim()}
              style={{ display: 'flex', alignItems: 'center', gap: '8px' }}
            >
              {isSending ? (
                <>
                  <div className="spinner-small" />
                  <span>Transmitting...</span>
                </>
              ) : (
                <>
                  <Send size={15} />
                  <span>Send Email</span>
                </>
              )}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
}
